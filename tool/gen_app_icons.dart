// Generates every platform's app icon and launch (splash) image from the
// original game's art.
//
//   fvm dart run tool/gen_app_icons.dart
//
// Input (committed):
//   tool/branding/turret_red.png               the original Red turret with its missile
//                                              launcher (`TurretRed`, symbol 910), exported
//                                              from .legacy/Onslaught2.swf with FFDec at
//                                              -zoom 48 (see tool/branding/README.md)
//   assets/images/classic/ground_classic@3x.jpg the classic ground texture
// Output (committed): Android mipmaps (legacy + adaptive) and splash drawables,
// iOS AppIcon + LaunchImage, macOS AppIcon, web icons + favicon, Windows .ico.
// Re-run after changing the inputs or the layout constants below.
// ignore_for_file: avoid_print

import 'dart:io';
import 'dart:math' as math;

import 'package:image/image.dart' as img;

const _turretPath = 'tool/branding/turret_red.png';
const _groundPath = 'assets/images/classic/ground_classic@3x.jpg';

/// Share of a full-bleed icon the turret covers.
const double _fullBleed = 0.84;

/// Share of an adaptive/maskable foreground the turret covers (inside the
/// 66 % / 80 % safe zones of Android adaptive and web maskable icons).
const double _adaptive = 0.6;

/// macOS: the rounded tile covers 824/1024 of the canvas (Apple's grid),
/// the turret 80 % of the tile.
const double _macTile = 824 / 1024;
const double _macTurret = 0.8;

late final img.Image _turret;
late final img.Image _ground;

void main() {
  _turret = img.decodePng(File(_turretPath).readAsBytesSync())!;
  final g = img.decodeJpg(File(_groundPath).readAsBytesSync())!;
  final side = math.min(g.width, g.height);
  _ground = img.copyCrop(
    g,
    x: (g.width - side) ~/ 2,
    y: (g.height - side) ~/ 2,
    width: side,
    height: side,
  );

  _android();
  _ios();
  _macos();
  _web();
  _windows();
  print('Wrote app icons and launch images');
}

img.Image _resize(img.Image src, int size) =>
    img.copyResize(src, width: size, height: size, interpolation: img.Interpolation.average);

/// The turret, [fraction] of [size], centred on [canvas].
img.Image _withTurret(img.Image canvas, int size, double fraction) {
  final t = _resize(_turret, (size * fraction).round());
  return img.compositeImage(canvas, t, dstX: (size - t.width) ~/ 2, dstY: (size - t.height) ~/ 2);
}

img.Image _blank(int size) => img.Image(width: size, height: size, numChannels: 4);

/// The full-bleed icon: the turret on the ground.
img.Image _icon(int size) => _withTurret(_resize(_ground, size), size, _fullBleed);

/// The turret alone on transparency, [fraction] of [size].
img.Image _foreground(int size, double fraction) => _withTurret(_blank(size), size, fraction);

void _write(String path, img.Image image) {
  File(path)
    ..createSync(recursive: true)
    ..writeAsBytesSync(img.encodePng(image));
}

void _android() {
  const res = 'android/app/src/main/res';
  // Legacy icons are 48 dp, adaptive layers 108 dp, the splash image 160 dp.
  const densities = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0};
  densities.forEach((d, scale) {
    _write('$res/mipmap-$d/ic_launcher.png', _icon((48 * scale).round()));
    final layer = (108 * scale).round();
    _write('$res/mipmap-$d/ic_launcher_foreground.png', _foreground(layer, _adaptive));
    _write('$res/mipmap-$d/ic_launcher_background.png', _resize(_ground, layer));
    _write('$res/drawable-$d/splash.png', _foreground((160 * scale).round(), 1));
    // Android 12+ draws the splash icon at 288 dp inside a 192 dp circle.
    _write('$res/drawable-$d/splash_icon.png', _foreground((288 * scale).round(), 0.85));
  });
  File('$res/mipmap-anydpi-v26/ic_launcher.xml')
    ..createSync(recursive: true)
    ..writeAsStringSync('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/gen_app_icons.dart -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
''');
}

void _ios() {
  const set = 'ios/Runner/Assets.xcassets';
  // AppIcon: the sizes its Contents.json lists (pt × scale); no alpha.
  const icons = {
    'Icon-App-20x20@1x.png': 20,
    'Icon-App-20x20@2x.png': 40,
    'Icon-App-20x20@3x.png': 60,
    'Icon-App-29x29@1x.png': 29,
    'Icon-App-29x29@2x.png': 58,
    'Icon-App-29x29@3x.png': 87,
    'Icon-App-40x40@1x.png': 40,
    'Icon-App-40x40@2x.png': 80,
    'Icon-App-40x40@3x.png': 120,
    'Icon-App-60x60@2x.png': 120,
    'Icon-App-60x60@3x.png': 180,
    'Icon-App-76x76@1x.png': 76,
    'Icon-App-76x76@2x.png': 152,
    'Icon-App-83.5x83.5@2x.png': 167,
    'Icon-App-1024x1024@1x.png': 1024,
  };
  icons.forEach((name, size) {
    _write('$set/AppIcon.appiconset/$name', _icon(size).convert(numChannels: 3));
  });
  // LaunchImage: the turret at 128 pt on the storyboard's backdrop colour.
  for (final (suffix, scale) in [('', 1), ('@2x', 2), ('@3x', 3)]) {
    _write('$set/LaunchImage.imageset/LaunchImage$suffix.png', _foreground(128 * scale, 1));
  }
}

void _macos() {
  const set = 'macos/Runner/Assets.xcassets/AppIcon.appiconset';
  for (final size in [16, 32, 64, 128, 256, 512, 1024]) {
    final tile = (size * _macTile).round();
    final inset = (size - tile) ~/ 2;
    final mask = img.fillRect(
      _blank(size),
      x1: inset,
      y1: inset,
      x2: inset + tile - 1,
      y2: inset + tile - 1,
      radius: tile * 0.225,
      color: img.ColorRgba8(255, 255, 255, 255),
    );
    final ground = img.compositeImage(
      _blank(size),
      _resize(_ground, tile),
      dstX: inset,
      dstY: inset,
    );
    final out = _blank(size);
    img.compositeImage(out, ground, mask: mask, maskChannel: img.Channel.alpha);
    final t = _resize(_turret, (tile * _macTurret).round());
    img.compositeImage(out, t, dstX: (size - t.width) ~/ 2, dstY: (size - t.height) ~/ 2);
    _write('$set/app_icon_$size.png', out);
  }
}

void _web() {
  for (final size in [192, 512]) {
    _write('web/icons/Icon-$size.png', _icon(size));
    _write(
      'web/icons/Icon-maskable-$size.png',
      _withTurret(_resize(_ground, size), size, _adaptive * 4 / 3),
    );
  }
  _write('web/favicon.png', _icon(32));
}

void _windows() {
  final frames = [
    for (final s in [16, 24, 32, 48, 64, 128, 256]) _icon(s),
  ];
  File('windows/runner/resources/app_icon.ico')
      .writeAsBytesSync(img.IcoEncoder().encodeImages(frames));
}
